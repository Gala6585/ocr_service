"""Создать локальный Compose override, если DNS сборщика недоступен, а DNS хоста работает."""

from pathlib import Path
import socket

ROOT = Path(__file__).resolve().parents[1]
MARKER = "# Generated by tools/refresh_build_hosts.py"
DOMAINS = (
    "pypi.org",
    "files.pythonhosted.org",
    "deb.debian.org",
    "security.debian.org",
    "download.pytorch.org",
    "download-r2.pytorch.org",
    "github.com",
    "release-assets.githubusercontent.com",
    "objects.githubusercontent.com",
)


if __name__ == "__main__":
    target = ROOT / "compose.override.yaml"
    if target.exists() and not target.read_text(encoding="utf-8").startswith(MARKER + "\n"):
        raise SystemExit("В проекте уже есть собственный compose.override.yaml.")
    lines = [MARKER, "x-build-hosts: &build-hosts"]
    for domain in DOMAINS:
        lines.append(f'  - "{domain}:{socket.gethostbyname(domain)}"')
    lines.append("services:")
    for name in ("flask", "streamlit", "rq-worker"):
        lines.extend([f"  {name}:", "    build:", "      extra_hosts: *build-hosts"])
        if name == "rq-worker":
            lines.append("    extra_hosts: *build-hosts")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
